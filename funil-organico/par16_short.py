def _caminho_do_painel(n=200):
    """⛔⛔ O CAMINHO QUE O `--autoteste` NUNCA PERCORRIA (2026-08-16).

    O motor saia `0 ERRO` em 400 sorteios e mesmo assim o painel entregava
    video quebrado, porque o autoteste chama `sortear -> montar -> lint` e o
    operador clica em `re-sortear copy`, que e' outro caminho inteiro:
    `ui_agente.trocar_fala -> nova_fala -> _gravar_fala -> _render`.

    ⚠️ Aqui esse caminho e' REPRODUZIDO, nao descrito — as tres funcoes da UI
    estao copiadas do `ui_agente.py` (linhas 1198-1218) sem tkinter. Medido
    antes do conserto: par hook/prova quebrado em 200 de 200 e apelido
    divergente entre os takes em 140 de 200 (CT4 + `PR15`).
    ⛔ Relato nao e' medicao: e' por isso que isto e' um teste e nao um
    paragrafo no cabecalho.
    """
    def _puras(spec):
        p = spec.get("_falas_puras")
        if p is None or len(p) != len(spec["falas"]):
            p = spec["_falas_puras"] = list(spec["falas"])
        spec["falas"] = sc.aplicar_keyword(p, KEYWORD_NATIVA)

    def _gravar(spec, i, texto):
        spec["falas"][i] = texto
        p = spec.get("_falas_puras")
        if p is not None and i < len(p):
            p[i] = sc.trocar_keyword(texto, sc.keyword(), KEYWORD_NATIVA)

    quebrados = divergentes = 0
    for s in range(n):
        rng = random.Random(s)
        sp = sortear("joe", rng, {})
        _puras(sp)                              # o painel faz isto ao abrir
        i = s % 2
        antes = list(sp["falas"])
        for _ in range(8):
            cand = nova_fala(sp, i, rng)
            if cand != antes[i]:
                break
        _gravar(sp, i, cand)
        _puras(sp)                              # o `_render` logo depois
        if [t for nv, t in lint(sp, montar(sp)) if nv == "ERRO"]:
            quebrados += 1
        o = [{x for x in NUCLEO if x.lower() in f.lower()} for f in sp["falas"]]
        if o[0] and o[1] and o[0] != o[1]:
            divergentes += 1
    falhas = []
    if quebrados:
        falhas.append("PAINEL: %d de %d cliques em `re-sortear copy` deixam o "
                      "lint sujo" % (quebrados, n))
    if divergentes:
        falhas.append("PAINEL: %d de %d cliques deixam o APELIDO divergente "
                      "entre os takes (CT4/PR15)" % (divergentes, n))
    return falhas


def _eixos_das_maos():
    """⛔ Contar entradas nao e' contar eixos: prova que qualquer par de maos
    difere em pelo menos TRES dos quatro eixos."""
    falhas = []
    for i, a in enumerate(MAOS):
        for b in MAOS[i + 1:]:
            n = sum(1 for e in EIXOS_MAO if a[e] != b[e])
            if n < 3:
                falhas.append("%s x %s diferem em so' %d eixo(s)"
                              % (a["id"], b["id"], n))
    return falhas


def _varredura_exaustiva():
    """⛔ AS 160 COMBINACOES, UMA A UMA — nao por amostragem.

    ⚠️ 400 sorteios aleatorios alcancam ~149 das 160, e as 11 que faltam sao
    justamente as que ninguem viu. Alcance medido por sorteio prova que o pool
    respira; so' a varredura prova que NENHUMA combinacao da' ERRO.
    """
    falhas, vistas = [], 0
    for m in MUNDOS:
        for f in FAMILIAS:
            for a in ACOES_T2:
                rng = random.Random(vistas)
                sp = sortear("joe", rng, {}, travas={
                    "cena": m["id"], "familia": f["id"], "acao": a["id"]})
                bl = montar(sp)
                ruins = [t for n, t in lint(sp, bl) if n == "ERRO"]
                if ruins:
                    falhas.append("%s x %s x %s: %s"
                                  % (m["id"], f["id"], a["id"], ruins[0][:60]))
                vistas += 1
    return falhas, vistas


def _teto_dos_blocos():
    """⛔⛔ O TAMANHO NAO SE MEDE POR AMOSTRAGEM — varre os QUATRO eixos que
    engordam o bloco, no PIOR valor de cada um dos que nao sao sorteados.

    ⚠️ A `_varredura_exaustiva` cruza mundo x familia x gesto e deixa as MAOS no
    sorteio — e as maos valem ate' 219 caracteres, 69 a mais que a menor. Um
    teto medido com maos medias e' um teto que passa no autoteste e estoura no
    campo. Aqui as maos entram na varredura, a idade e' travada na mais longa
    (`seventy-one`, 2 chars a mais que `sixty-two`) e o apelido no mais longo.
    ⭐ E o gesto vem de `ACOES_T2_TODAS`, nao de `ACOES_T2`: o `dedo_no_marrom`
    esta' fora do sorteio mas ALCANCAVEL pela trava do painel, e bloco cortado
    por caminho de trava e' cortado do mesmo jeito.

    Devolve (falhas, piores) — `piores[bloco] = (chars, mundo)`.
    """
    idade = max(IDADES, key=len)
    orgao = max(sc.APELIDOS_16, key=len)
    falhas, piores = [], {}
    for m in MUNDOS:
        for f in FAMILIAS:
            for a in ACOES_T2_TODAS:
                for mo in MAOS:
                    sp = sortear("joe", random.Random(0), {}, travas={
                        "cena": m["id"], "familia": f["id"], "acao": a["id"],
                        "maos": mo["id"]})
                    sp["idade"], sp["orgao"] = idade, orgao
                    sp["falas"] = _montar_falas(sp)
                    for k, txt in montar(sp).items():
                        if len(txt) > piores.get(k, (0, ""))[0]:
                            piores[k] = (len(txt), m["id"])
                        if len(txt) > TETO_BLOCO:
                            falhas.append(
                                "PR20: %s em %s x %s x %s x %s -> %d chars "
                                "(teto %d)" % (k, m["id"], f["id"], a["id"],
                                               mo["id"], len(txt), TETO_BLOCO))
    return falhas[:6], piores


def _autoteste(n=400, seed=20260816):
    try:
        falhas = _controles_negativos()
    except AssertionError as e:                          # ancora do plantio
        falhas = ["CONTROLE NEGATIVO QUEBRADO: %s" % e]
    falhas += _eixos_das_maos()
    falhas += _caminho_do_painel()
    falhas += sc.autoteste_anticeleb()
    falhas_comb, vistas = _varredura_exaustiva()
    falhas += falhas_comb
    falhas_teto, piores = _teto_dos_blocos()
    falhas += falhas_teto

    rng = random.Random(seed)
    led, erros = {}, collections.Counter()
    cont = {e: collections.Counter() for e in EIXOS_LEDGER}
    cont["orgao"] = collections.Counter()
    trios = set()
    falas = {1: set(), 2: set()}
    pal = {1: [], 2: []}
    paginas = ("joe", "marcus", "ray", "chuck", "matt")
    for i in range(n):
        sp = sortear(paginas[i % len(paginas)], rng, led)
        _anotar(led, sp)
        bl = montar(sp)
        for nivel, txt in lint(sp, bl):
            if nivel == "ERRO":
                erros[txt.split(":")[0]] += 1
        for e in EIXOS_LEDGER:
            cont[e][sp[e]["id"]] += 1
        cont["orgao"][sp["orgao"]] += 1
        trios.add((sp["cena"]["id"], sp["familia"]["id"], sp["acao"]["id"]))
        for j in (1, 2):
            falas[j].add(sp["falas"][j - 1])
            pal[j].append(_palavras(sp["falas"][j - 1]))

    print("%s — %d sorteios pelas 5 paginas (seed %d)" % (APP, n, seed))
    for e, pool in (("cena", MUNDOS), ("familia", FAMILIAS),
                    ("acao", ACOES_T2), ("maos", MAOS)):
        c = cont[e]
        print("  %-8s %d de %d alcancados · min %d · max %d"
              % (e, len(c), len(pool), min(c.values()), max(c.values())))
    print("  orgao    %s" % dict(cont["orgao"]))
    print("  combinacoes mundo x familia x gesto: %d de %d vistas no sorteio · "
          "%d de %d VARRIDAS uma a uma"
          % (len(trios), len(MUNDOS) * len(FAMILIAS) * len(ACOES_T2),
             vistas, len(MUNDOS) * len(FAMILIAS) * len(ACOES_T2)))
    for j in (1, 2):
        print("  cena %d: %3d falas distintas · palavras %d/%d/%d (teto %d)"
              % (j, len(falas[j]), min(pal[j]), sum(pal[j]) // len(pal[j]),
                 max(pal[j]), TETO_FALA[j]))
    print("  pools: %d mundos (%d transpostos) · %d familias · %d gestos · "
          "%d maos" % (len(MUNDOS), sum(1 for m in MUNDOS if m["transposto"]),
                       len(FAMILIAS), len(ACOES_T2), len(MAOS)))
    # ⭐ O MAIOR BLOCO DE CADA TIPO — a AdBatch corta em 4.000 EM SILENCIO, e
    # ate' 2026-08-16 este numero nao era impresso em lugar nenhum.
    print("  MAIOR bloco de cada tipo (varredura de tamanho, %d montagens, "
          "teto %d):" % (len(MUNDOS) * len(FAMILIAS) * len(ACOES_T2_TODAS)
                         * len(MAOS), TETO_BLOCO))
    for k in sorted(piores):
        chars, mundo = piores[k]
        print("     %-14s %4d  (%s)  folga %d%s"
              % (k, chars, mundo, TETO_BLOCO - chars,
                 "" if chars <= TETO_BLOCO else "   ⛔ ESTOURO"))
    print("  controles negativos: %d falha(s)" % len(falhas))
    for f in falhas[:8]:
        print("     %s" % f)
    print("  linter: %d ERRO" % sum(erros.values()))
    for k, v in erros.most_common(8):
        print("     %4dx %s" % (v, k))
    return sum(erros.values()) + len(falhas)


