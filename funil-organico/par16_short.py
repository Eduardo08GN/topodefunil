def _sabotar(blocos, chave, de, para):
    """Planta o defeito e PROVA que ele chegou ao texto.

    ⛔ Sem o `assert` o controle morre calado no dia em que a prosa do bloco
    muda: a ancora deixa de existir, o `replace` nao faz nada, a lente nao
    acusa — e o placar diz que a lente esta' cega. Aconteceu aqui, com o
    `PR13`, na primeira reescrita do IMAGE.
    """
    if de not in blocos[chave]:
        raise AssertionError("a ancora %r nao existe em %s — o controle "
                             "negativo nao chegaria ao texto" % (de, chave))
    b = dict(blocos)
    b[chave] = b[chave].replace(de, para, 1)
    return b


