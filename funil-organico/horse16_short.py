def _carregar_ledger():
    if not os.path.isfile(LEDGER):
        return {}
    try:
        with io.open(LEDGER, encoding="utf-8") as f:
            return json.load(f)
    except (ValueError, IOError):
        return {}


def _gravar_ledger(ledger, spec=None):
    # ⚠️ Os eixos gravados sao os que TEM `id` e chegam ao quadro. `acao` entra
    # porque e' o eixo principal deste motor: sem memoria nele, o pool de cinco
    # repetiria o mesmo gesto em lotes seguidos, que e' o defeito que o PEE 16
    # pagou (pool grande com sorteio sem memoria repete igual).
    if spec is not None:
        for eixo in ("balcao", "superficie", "caixa", "rotulo", "receita",
                     "acao", "maos", "ela"):
            v = spec.get(eixo)
            if isinstance(v, dict):
                ledger.setdefault(eixo, []).append(v["id"])
                ledger[eixo] = ledger[eixo][-24:]
    try:
        with io.open(LEDGER, "w", encoding="utf-8") as f:
            f.write(json.dumps(ledger, ensure_ascii=False, indent=1))
    except IOError:
        pass


