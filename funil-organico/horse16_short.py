# ⛔ ACEITE E' MEDICAO, NUNCA RELATO. Ele mede o alcance de cada pool (entrada
# que nunca sai esta' morta e o autoteste de contagem a conta como viva), o
# minimo e o maximo de palavras por cena (o MINIMO decide o teto, nao o maximo)
# e os dois estados do MODO BELA.

def autoteste(n=400):
    pags = sorted(ETNIA)
    erros = collections.Counter()
    avisos = 0
    dist = collections.defaultdict(set)
    tam = collections.defaultdict(list)
    falhas = []
    rng = random.Random(20260814)

    for i in range(n):
        pag = pags[i % len(pags)]
        travas = {"bela": True} if i % 2 else {}
        spec = sortear(pag, rng, {}, travas)
        bl = montar(spec)
        for j, fala in enumerate(spec["falas"], 1):
            tam[j].append(_palavras(fala))
        for eixo in ("balcao", "superficie", "caixa", "rotulo", "receita",
                     "acao", "maos", "ela"):
            dist[eixo].add(spec[eixo]["id"])
        for nivel, msg in lint(spec, bl):
            if nivel == "ERRO":
                erros[msg[:78]] += 1
                if len(falhas) < 3:
                    falhas.append((pag, msg, list(spec["falas"])))
            else:
                avisos += 1

    print("%s — %d sorteios, %d paginas" % (TITULO, n, len(pags)))
    for j in sorted(tam):
        v = tam[j]
        print("  cena %d: %2d-%2d palavras (piso %d, teto %d), media %.1f"
              % (j, min(v), max(v), PISO_FALA[j], TETO_FALA[j],
                 sum(v) / float(len(v))))
    for eixo, pool in (("balcao", BALCOES), ("superficie", SUPERFICIES),
                       ("caixa", CAIXAS), ("rotulo", ROTULOS),
                       ("receita", RECEITAS), ("acao", ACOES),
                       ("maos", MAOS), ("ela", ELAS)):
        marca = "" if len(dist[eixo]) == len(pool) else "   <-- entrada morta"
        print("  %-11s %2d/%2d alcancadas%s"
              % (eixo, len(dist[eixo]), len(pool), marca))
    print("  AVISOS: %d" % avisos)
    if erros:
        print("  ERROS:")
        for msg, q in erros.most_common():
            print("    %4d x %s" % (q, msg))
        for pag, msg, fs in falhas:
            print("    --- %s: %s" % (pag, msg))
            for f in fs:
                print("        %s" % f)
        return False
    print("  OK: zero ERRO em %d sorteios" % n)
    return True


