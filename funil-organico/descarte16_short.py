def _grams_partilhados(pool, campo, n=4):
    """Os n-gramas que aparecem em DUAS ou mais entradas do mesmo pool."""
    porkey, conta = {}, collections.Counter()
    for x in pool:
        bruto = x[campo].replace("%s", "X")
        for inv in _INVARIANTES_DE_FORMA:
            bruto = bruto.replace(inv, " . ")
        t = _tokens(bruto)
        gs = {" ".join(t[i:i + n]) for i in range(len(t) - n + 1)}
        porkey[_chave(x)] = gs
        for g in gs:
            conta[g] += 1
    repetidos = {g for g, c in conta.items() if c > 1}
    return ({k: (gs & repetidos) for k, gs in porkey.items()},
            collections.Counter({g: conta[g] for g in repetidos}))


